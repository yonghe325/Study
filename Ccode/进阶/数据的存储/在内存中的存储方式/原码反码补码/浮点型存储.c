#include<stdio.h>
int main() {
	int n = 9;
	//00000000 00000000 00000000 00001001

	float* pFloat = (float*)&n;

	printf("n的值为: %d\n", n);
	//以%d的形式打印

	printf("*pFloat的值为 : %f\n", *pFloat);
	//浮点数的规则解读n的二进制值
	//0 00000000 00000000000000000001001
	// s=0  e=0 m=0.00000000000000000001001
	//即为
	//+0.0.00000000000000000001001 * 2^-126
	//无限接近于0
	//打印0.0000000
	// 

	*pFloat = 9.0;
	//以浮点型的方式放入数值
	//1001.0
	//1.001* 2^3
	//s=0  e=3 m=1.001
	//0 10000010 00100000000000000000000
	//n的内存空间则被放入
	//01000001 00010000 00000000 00000000
	//01000001000100000000000000000000

 	printf("num的值为: %d\n", n);
	//将n以%d的方式打印
	//1091567616
	printf("*pFloat的值为 : %f\n", *pFloat);
	return 0;
}

